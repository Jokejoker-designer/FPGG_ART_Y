#!/usr/bin/env python3
"""U4-PRE0 host golden: P4_4k_h64 directory address law.

dir_addr = INDEX_BASE + table_id * 65536 + bucket_id * 16
bucket_id = k & 0xFFF
No synthetic keys. No silent 16-bucket reduce.
"""
from __future__ import annotations

import json
from pathlib import Path

BAG = Path(__file__).resolve().parent
INDEX_BASE = 0x05000000
N_TABLES = 4
N_BUCKETS = 4096
BUCKET_W = 12
ENTRY_BYTES = 16
TABLE_BYTES = N_BUCKETS * ENTRY_BYTES  # 65536
CAND_CAP = 64
ALIAS_K = [0x001, 0x011, 0x101, 0x201, 0xFFF]
MAP_K = [0x00AA, 0x00BB, 0x00CC, 0x00DD]


def dir_addr(table: int, key: int) -> int:
    bucket = key & ((1 << BUCKET_W) - 1)
    return INDEX_BASE + table * TABLE_BYTES + bucket * ENTRY_BYTES


def old16(table: int, key: int) -> int:
    """Legacy 16-bucket truncation (B_W=4). Must NOT equal 4096-law for alias keys."""
    return INDEX_BASE + table * (16 * 16) + (key & 0xF) * ENTRY_BYTES


def xor_synth_t2(k0: int, k1: int) -> int:
    """Forbidden key_of(t>=2) = k0 ^ k1 ^ table."""
    return (k0 ^ k1 ^ 2) & 0xFFF


def main() -> int:
    # 1. Full uniqueness 4 * 4096
    seen: dict[int, tuple[int, int]] = {}
    overlap = []
    for t in range(N_TABLES):
        for b in range(N_BUCKETS):
            a = dir_addr(t, b)
            if a in seen:
                overlap.append((t, b, a, seen[a]))
            else:
                seen[a] = (t, b)
    n_unique = len(seen)
    expect_n = N_TABLES * N_BUCKETS
    bases = [INDEX_BASE + t * TABLE_BYTES for t in range(N_TABLES)]
    last = [bases[t] + (N_BUCKETS - 1) * ENTRY_BYTES for t in range(N_TABLES)]
    disjoint = all(last[t] < bases[t + 1] for t in range(N_TABLES - 1))

    # 2. Alias vectors vs old 16-bucket
    alias = []
    for k in ALIAS_K:
        a12 = dir_addr(0, k)
        a4 = old16(0, k)
        alias.append({
            "key": k,
            "key_hex": f"0x{k:03X}",
            "addr_12": a12,
            "addr_12_hex": f"0x{a12:08X}",
            "addr_old16": a4,
            "addr_old16_hex": f"0x{a4:08X}",
            "bucket_12": k & 0xFFF,
            "bucket_old16": k & 0xF,
        })
    alias_addrs = [x["addr_12"] for x in alias]
    alias_unique = len(set(alias_addrs)) == len(alias_addrs)
    k001_011_aliased_old = old16(0, 0x001) == old16(0, 0x011)
    k001_011_distinct_new = dir_addr(0, 0x001) != dir_addr(0, 0x011)

    # 3. Exact T0..T3 vs XOR fake T2
    exact = [dir_addr(t, MAP_K[t]) for t in range(4)]
    xor_b = xor_synth_t2(MAP_K[0], MAP_K[1])
    xor_t2 = dir_addr(2, xor_b)

    fail = []
    if TABLE_BYTES != 65536:
        fail.append("TABLE_BYTES")
    if n_unique != expect_n or overlap:
        fail.append("OVERLAP")
    if not disjoint:
        fail.append("NOT_DISJOINT")
    if bases != [INDEX_BASE, INDEX_BASE + 0x10000, INDEX_BASE + 0x20000, INDEX_BASE + 0x30000]:
        fail.append("BASES")
    if not alias_unique:
        fail.append("ALIAS_NOT_UNIQUE_12")
    if not k001_011_aliased_old:
        fail.append("OLD16_DID_NOT_ALIAS")  # the test itself is wrong
    if not k001_011_distinct_new:
        fail.append("NEW12_STILL_ALIASES")
    if exact[2] == xor_t2:
        fail.append("T2_COLLIDES_WITH_XOR_SYNTH")

    result = "PASS" if not fail else "FAIL"
    out = {
        "gate": "U4-PRE0-SPARSE-DIR-GEOMETRY-AUTHORITY-00",
        "index_base": INDEX_BASE,
        "n_tables": N_TABLES,
        "n_buckets": N_BUCKETS,
        "bucket_w": BUCKET_W,
        "entry_bytes": ENTRY_BYTES,
        "table_bytes": TABLE_BYTES,
        "cand_cap": CAND_CAP,
        "bases": [f"0x{b:08X}" for b in bases],
        "last": [f"0x{a:08X}" for a in last],
        "n_unique_dir_addr": n_unique,
        "expect_unique": expect_n,
        "disjoint_table_ranges": disjoint,
        "overlap_count": len(overlap),
        "alias": alias,
        "alias_unique_under_12bit": alias_unique,
        "old16_aliases_0x001_0x011": k001_011_aliased_old,
        "new12_distinct_0x001_0x011": k001_011_distinct_new,
        "map_keys": [f"0x{k:04X}" for k in MAP_K],
        "exact_dir": [f"0x{a:08X}" for a in exact],
        "xor_synth_t2_bucket": xor_b,
        "xor_synth_t2_addr": f"0x{xor_t2:08X}",
        "result": result,
        "fail_reasons": fail,
    }
    (BAG / "GOLDEN.json").write_text(json.dumps(out, indent=2), encoding="utf-8")

    def hx28(a: int) -> str:
        return f"28'h{a:08X}"

    svh = [
        "// generated by host_geometry.py — do not hand-edit",
        f"localparam logic [27:0] G_INDEX_BASE = {hx28(INDEX_BASE)};",
        f"localparam int unsigned G_TABLE_BYTES = {TABLE_BYTES};",
        f"localparam int unsigned G_N_BUCKETS = {N_BUCKETS};",
        f"localparam int unsigned G_CAND_CAP = {CAND_CAP};",
    ]
    for t, b in enumerate(bases):
        svh.append(f"localparam logic [27:0] G_T{t}_BASE = {hx28(b)};")
    svh.append("localparam int unsigned G_N_ALIAS = 5;")
    svh.append(
        "localparam logic [15:0] G_ALIAS_K [0:4] = '{"
        + ", ".join(f"16'h{k:04X}" for k in ALIAS_K)
        + "};"
    )
    svh.append(
        "localparam logic [27:0] G_ALIAS_A [0:4] = '{"
        + ", ".join(hx28(dir_addr(0, k)) for k in ALIAS_K)
        + "};"
    )
    svh.append(
        "localparam logic [15:0] G_MAP_K [0:3] = '{"
        + ", ".join(f"16'h{k:04X}" for k in MAP_K)
        + "};"
    )
    svh.append(
        "localparam logic [27:0] G_MAP_A [0:3] = '{"
        + ", ".join(hx28(exact[t]) for t in range(4))
        + "};"
    )
    svh.append(f"localparam logic [27:0] G_XOR_FAKE_T2 = {hx28(xor_t2)};")
    svh.append(f"localparam logic [27:0] G_OLD16_001 = {hx28(old16(0, 0x001))};")
    svh.append(f"localparam logic [27:0] G_OLD16_011 = {hx28(old16(0, 0x011))};")
    (BAG / "golden_addr.svh").write_text("\n".join(svh) + "\n", encoding="utf-8")

    print("TABLE_BYTES", TABLE_BYTES)
    print("BASES", [f"0x{b:08X}" for b in bases])
    print("UNIQUE", n_unique, "expect", expect_n, "disjoint", disjoint)
    print("ALIAS", [(f"0x{k:03X}", f"0x{dir_addr(0, k):08X}", f"old16=0x{old16(0, k):08X}") for k in ALIAS_K])
    print("EXACT", [f"0x{a:08X}" for a in exact], "XOR_T2", f"0x{xor_t2:08X}")
    print("RESULT", result, fail)
    print("U4_PRE0_HOST_GEOMETRY_DONE")
    return 0 if result == "PASS" else 7


if __name__ == "__main__":
    raise SystemExit(main())
